using System.Globalization;
using System.Text;
using System.Text.Json;
using CsvHelper;
using ModScope.Core.Models;
using ModScope.Diagnostics.Monitoring;
using ModScope.Diagnostics.Sequences;
using ModScope.ModbusMaster;

namespace ModScope.Infrastructure.Reporting;

/// <summary>
/// Professional diagnostic reporting and data export service (CSV, JSON, Markdown/HTML summary).
/// </summary>
public class DiagnosticReportService
{
    /// <summary>
    /// Exports monitored registers to CSV format.
    /// </summary>
    public static void ExportRegistersToCsv(IEnumerable<ModbusRegisterItem> items, string filePath)
    {
        using var writer = new StreamWriter(filePath);
        using var csv = new CsvWriter(writer, CultureInfo.InvariantCulture);
        csv.WriteRecords(items);
    }

    /// <summary>
    /// Exports captured frames to CSV.
    /// </summary>
    public static void ExportFramesToCsv(IEnumerable<ModbusRawFrame> frames, string filePath)
    {
        using var writer = new StreamWriter(filePath);
        using var csv = new CsvWriter(writer, CultureInfo.InvariantCulture);
        
        var dtos = frames.Select(f => new
        {
            Timestamp = f.Timestamp.ToString("yyyy-MM-dd HH:mm:ss.fff"),
            Direction = f.Direction.ToString(),
            f.Length,
            RawHex = f.HexString,
            f.Description,
            f.IsError
        });

        csv.WriteRecords(dtos);
    }

    /// <summary>
    /// Generates a comprehensive commissioning and diagnostic assessment report in Markdown/HTML.
    /// </summary>
    public static string GenerateDiagnosticSummaryReport(
        ConnectionConfig config,
        CommunicationHealthMetrics metrics,
        IEnumerable<SequenceStep>? sequenceSteps = null,
        IEnumerable<AuditLogEntry>? auditTrail = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# ModScope Industrial Modbus Diagnostic Report");
        sb.AppendLine($"**Generated:** {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine("## 1. Connection Parameters");
        sb.AppendLine($"- **Protocol / Type:** Modbus {config.ConnectionType}");
        if (config.ConnectionType == ConnectionType.Tcp)
        {
            sb.AppendLine($"- **Endpoint:** `{config.Host}:{config.Port}`");
        }
        else
        {
            sb.AppendLine($"- **Serial Port:** `{config.SerialPortName}` ({config.BaudRate} baud, 8-{config.Parity.ToString()[0]}-{config.StopBits})");
        }
        sb.AppendLine($"- **Timeout:** {config.TimeoutMs} ms");
        sb.AppendLine();

        sb.AppendLine("## 2. Communication Health & Telemetry");
        sb.AppendLine($"| Metric | Value |");
        sb.AppendLine($"| :--- | :--- |");
        sb.AppendLine($"| Total Transactions | {metrics.TotalTransactions} |");
        sb.AppendLine($"| Successful Transactions | {metrics.SuccessfulTransactions} |");
        sb.AppendLine($"| Packet Success Rate | {metrics.PacketSuccessRate}% |");
        sb.AppendLine($"| CRC-16 Checksum Errors | {metrics.CrcErrors} |");
        sb.AppendLine($"| Response Timeouts | {metrics.TimeoutErrors} |");
        sb.AppendLine($"| Modbus Exception Responses | {metrics.ProtocolExceptions} |");
        sb.AppendLine($"| Average Latency | {metrics.AverageResponseTimeMs:F2} ms |");
        sb.AppendLine();

        if (sequenceSteps != null && sequenceSteps.Any())
        {
            sb.AppendLine("## 3. Commissioning Sequence Results");
            sb.AppendLine("| Step # | Name | Status | Duration | Details |");
            sb.AppendLine("| :--- | :--- | :--- | :--- | :--- |");
            foreach (var step in sequenceSteps)
            {
                sb.AppendLine($"| {step.StepNumber} | {step.Name} | **{step.Status}** | {step.Duration.TotalMilliseconds:F0} ms | {step.ResultMessage} |");
            }
            sb.AppendLine();
        }

        if (auditTrail != null && auditTrail.Any())
        {
            sb.AppendLine("## 4. Audit Trail & Control Actions");
            sb.AppendLine("| Timestamp (UTC) | Operator | Operation | Slave | Addr | Old | New | Result |");
            sb.AppendLine("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |");
            foreach (var a in auditTrail)
            {
                sb.AppendLine($"| {a.Timestamp:HH:mm:ss.fff} | {a.OperatorName} | {a.Operation} | {a.SlaveId} | {a.Address} | {a.OldValue} | {a.NewValue} | {(a.Success ? "OK" : "FAILED")} |");
            }
            sb.AppendLine();
        }

        sb.AppendLine("---");
        sb.AppendLine("*Report generated by ModScope Cross-Platform Modbus Diagnostic Studio.*");
        return sb.ToString();
    }
}
